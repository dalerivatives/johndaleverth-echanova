const {chromium}=require('playwright');
const {spawn}=require('node:child_process'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'portfolio-v85-'));
const server=spawn(process.env.PYTHON||'python',['-m','uvicorn','backend.main:app','--port','8768'],{env:{...process.env,DATABASE_URL:'sqlite:///'+path.join(tmp,'test.db'),SPEECH_MODE:'static',ADMIN_KEY:'local-test-only'},stdio:'ignore'});
const wait=ms=>new Promise(r=>setTimeout(r,ms));let browser;
(async()=>{
 for(let i=0;i<100;i++){try{if((await fetch('http://127.0.0.1:8768/api/health')).ok)break}catch{}await wait(100)}
 browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await context.route(/^https:\/\//,r=>r.fulfill({body:''}));
 await context.addInitScript(()=>{Object.defineProperty(window,'speechSynthesis',{value:{getVoices:()=>[],cancel(){},addEventListener(){}}});Object.defineProperty(navigator,'deviceMemory',{value:2});});
 const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/settings',async route=>{await wait(1200);await route.continue()});
 await page.goto('http://127.0.0.1:8768/',{waitUntil:'domcontentloaded'});
 const loading=await page.evaluate(()=>({boot:document.documentElement.classList.contains('booting'),opacity:getComputedStyle(document.querySelector('.app')).opacity,portrait:getComputedStyle(document.querySelector('#asciiArt')).visibility,screen:getComputedStyle(document.querySelector('#bootScreen')).opacity}));
 assert(loading.boot);assert.equal(loading.opacity,'0');assert.equal(loading.screen,'1');
 await page.waitForFunction(()=>!document.documentElement.classList.contains('booting'));
 await page.waitForFunction(()=>document.querySelector('#bootScreen').hidden);
 await page.keyboard.press('F5');await wait(100);
 assert(await page.evaluate(()=>document.documentElement.classList.contains('boot-departing')));
 const alpha=await page.locator('#bootScreen').evaluate(el=>+getComputedStyle(el).opacity);
 assert(alpha>0 && alpha<1,'outgoing cover visibly fades');
 await page.waitForFunction(()=>document.documentElement.classList.contains('booting'));
 assert.equal(await page.locator('.app').evaluate(el=>getComputedStyle(el).opacity),'0');
 await page.waitForFunction(()=>document.querySelector('#bootScreen').hidden);
 await page.reload({waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('.app').evaluate(el=>getComputedStyle(el).opacity),'0');
 await page.waitForFunction(()=>document.querySelector('#bootScreen').hidden);
 await page.evaluate(()=>{dispatchEvent(new Event('beforeunload'));dispatchEvent(new PageTransitionEvent('pageshow',{persisted:true}));});
 assert(await page.locator('#bootScreen').evaluate(el=>el.hidden));
 assert.deepEqual(errors,[]);
 console.log('PASS: initial portrait suppression, animated F5 reload, native reload coverage, readiness release, cached-page restoration, no JS errors');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM')});
